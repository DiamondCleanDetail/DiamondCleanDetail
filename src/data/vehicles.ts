export const vehicleMakes = Object.keys(vehicleData).sort((a, b) => a.localeCompare(b));

export function getModelsForMake(make: string): VehicleModel[] {
  return [...(vehicleData[make] ?? [])].sort((a, b) => a.name.localeCompare(b.name));
}

export function getVehicleCategory(make: string, modelName: string): VehicleSize | null {
  const model = vehicleData[make]?.find((m) => m.name === modelName);
  return model?.category ?? null;
}

export const vehicleYears: number[] = Array.from(
  { length: new Date().getFullYear() + 1 - 2000 + 1 },
  (_, i) => new Date().getFullYear() + 1 - i
);
